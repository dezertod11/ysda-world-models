"""Index local reports without treating files or repeated analyses as evidence."""

import csv
import hashlib
import json
import re
import subprocess
from collections import Counter
from pathlib import Path
from urllib.parse import quote

from markdown_it import MarkdownIt


PUBLICATION = Path(__file__).resolve().parents[1]
PROJECT = PUBLICATION.parents[1]
MARKDOWN = MarkdownIt()


def category(path):
    parts = path.parts
    name = path.name.lower()
    if "reference" in parts:
        return "external_reference"
    if len(parts) == 2:
        if "result" in name or "synthesis" in name:
            return "research_report"
        return "protocol_or_navigation"
    if path.suffix == ".ipynb":
        return "notebook"
    if path.suffix == ".json":
        return "machine_summary"
    if path.suffix == ".html":
        return "video_gallery"
    if "smoke" in str(path).lower():
        return "technical_report"
    if "uncertainty" in parts:
        return "early_exploration"
    return "stage_report_or_notes"


def title(path, data):
    if path.suffix == ".html":
        return path.stem
    if path.suffix == ".json":
        json.loads(data)
        return path.stem
    if path.suffix == ".ipynb":
        notebook = json.loads(data)
        source = "\n".join(
            "".join(cell.get("source", []))
            for cell in notebook.get("cells", [])
            if cell.get("cell_type") == "markdown"
        )
    else:
        source = data.decode("utf-8")
    tokens = MARKDOWN.parse(source)
    for previous, current in zip(tokens, tokens[1:]):
        if previous.type == "heading_open" and current.type == "inline":
            return " ".join(current.content.split())
    return path.stem


def collect():
    # Ignore Git exclusions: local-only analysis artifacts also belong in the index.
    command = ["rg", "--files", "--no-ignore", "experiments",
               "-g", "*.md", "-g", "*RESULT*.ipynb", "-g", "*summary.json",
               "-g", "*videos*.html", "-g", "*gallery*.html"]
    paths = subprocess.run(command, cwd=PROJECT, check=True, capture_output=True,
                           text=True).stdout.splitlines()
    rows = []
    for relative in sorted(set(paths)):
        path = Path(relative)
        if any(part in {".git", ".ipynb_checkpoints", "__pycache__"} for part in path.parts):
            continue
        data = (PROJECT / path).read_bytes()
        date = re.search(r"20\d{6}", relative)
        rows.append({"path": relative, "category": category(path),
                     "title": title(path, data),
                     "date_token_from_path": date.group() if date else "",
                     "sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data)})
    return rows


def main():
    rows = collect()
    counts = Counter(row["category"] for row in rows)
    csv_path = PUBLICATION / "results_index.csv"
    with csv_path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    lines = ["# Local Results Source Index", "",
             "Generated by `tools/index_results.py`; content hashes are in [CSV](results_index.csv).",
             "This is a file inventory, NOT a count of experiments, independent samples, or confirmed claims.",
             "Read [the research synthesis](RESULTS_AND_ANALYSIS.md) for results and validity limits.",
             "Categories are based on paths, not an automatic scientific audit. Dates are filename tokens,",
             "not verified completion dates. Smoke, old analyses and external references are retained",
             "for provenance and must not be pooled into benchmark scores.", "",
             "Scope: all local experiments Markdown files, *RESULT*.ipynb, *summary.json,",
             "and *videos*.html / *gallery*.html, including Git-ignored files. Raw rollout",
             "JSON/NPZ/MP4 and individual CSVs remain linked from their reports, not copied here.",
             "Remote-only and unsynced results are not indexed. No process status is inferred.", "",
             "Regenerate from the project root:", "", "```bash",
             "/home/alexander/venvs/cosmos_policy_libero/bin/python publication/iclr2027/tools/index_results.py",
             "```", "", f"Local source files: **{len(rows)}**.", ""]
    for group in sorted(counts):
        lines.extend([f"## {group} ({counts[group]})", "",
                      "| Source | Title |", "|---|---|"])
        for row in rows:
            if row["category"] != group:
                continue
            label = row["path"].replace("|", "\\|")
            heading = row["title"].replace("|", "\\|").replace("[", "\\[").replace("]", "\\]")
            target = quote("../../" + row["path"], safe="/._-")
            lines.append(f"| [{label}]({target}) | {heading} |")
        lines.append("")
    (PUBLICATION / "RESULTS_INDEX.md").write_text("\n".join(lines), encoding="utf-8")
    print(json.dumps({"files": len(rows), "categories": dict(counts),
                      "output": str(csv_path)}, indent=2))


if __name__ == "__main__":
    main()
