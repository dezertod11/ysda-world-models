def _make_plot(
    holdout: pd.DataFrame,
    holdout_predictions: pd.DataFrame,
    holdout_policies: pd.DataFrame,
    best_pre: pd.Series,
    best_post: pd.Series,
    transfer_rows: pd.DataFrame,
    output_path: Path,
) -> None:
    fig, axes = plt.subplots(2, 2, figsize=(14, 10))
    colors = {
        "both_fail": "#777777",
        "both_success": "#3f6ea8",
        "harm": "#bd3f3f",
        "rescue": "#25865a",
    }
    for axis, chosen, title in (
        (axes[0, 0], best_pre, "Best pre-query OOF score"),
        (axes[0, 1], best_post, "Best post-query OOF score"),
    ):
        scoped = holdout_predictions.loc[
            holdout_predictions["model"].eq(chosen["model"])
        ]
        merged = holdout[["analysis_row_id", "terminal_outcome"]].merge(
            scoped[["analysis_row_id", "predicted_vof_mean", "predicted_vof_std"]],
            on="analysis_row_id",
            validate="one_to_one",
        )
        score = merged["predicted_vof_mean"] - float(chosen["beta"]) * merged[
            "predicted_vof_std"
        ]
        order = ["both_fail", "both_success", "harm", "rescue"]
        for index, outcome in enumerate(order):
            values = score.loc[merged["terminal_outcome"].eq(outcome)].to_numpy(float)
            jitter = np.linspace(-0.12, 0.12, len(values)) if len(values) else np.array([])
            axis.scatter(
                np.full(len(values), index) + jitter,
                values,
                color=colors[outcome],
                alpha=0.85,
                label=outcome,
            )
        axis.axhline(0, color="black", linewidth=1)
        axis.set_xticks(range(len(order)), [value.replace("_", "\n") for value in order])
        axis.set_ylabel("OOF signed-VoF score")
        axis.set_title(f"{title}: {chosen['model']}, beta={chosen['beta']}")
        axis.grid(axis="y", alpha=0.25)

    axis = axes[1, 0]
    for chosen, label, color in (
        (best_pre, "pre-query", "#25865a"),
        (best_post, "post-query", "#7b5ea7"),
    ):
        curve = holdout_policies.loc[
            holdout_policies["model"].eq(chosen["model"])
            & holdout_policies["stage"].eq(chosen["stage"])
            & holdout_policies["selection_mode"].eq("ranked_budget")
            & holdout_policies["beta"].eq(chosen["beta"])
        ].sort_values("budget")
        axis.plot(
            100 * curve["budget"],
            100 * curve["adjusted_success_delta"],
            marker="o",
            color=color,
            label=label,
        )
    axis.axhline(0, color="black", linewidth=1)
    axis.set_xlabel("selected-tail budget (%)")
    axis.set_ylabel("cost-adjusted terminal gain (pp)")
    axis.set_title("Holdout-cohort grouped OOF budget curves")
    axis.grid(alpha=0.25)
    axis.legend()

    axis = axes[1, 1]
    labels = ["commit", "always\nrequery", "best pre\nOOF", "best post\nOOF"]
    always = holdout_policies.loc[holdout_policies["model"].eq("always_requery")].iloc[0]
    values = [
        0.0,
        100 * float(always["adjusted_success_delta"]),
        100 * float(best_pre["adjusted_success_delta"]),
        100 * float(best_post["adjusted_success_delta"]),
    ]
    bars = axis.bar(labels, values, color=["#666666", "#c58b36", "#25865a", "#7b5ea7"])
    axis.axhline(0, color="black", linewidth=1)
    axis.set_ylabel("cost-adjusted terminal gain (pp)")
    axis.set_title("Development policy comparison")
    for bar, value in zip(bars, values):
        axis.text(bar.get_x() + bar.get_width() / 2, value, f"{value:+.1f}", ha="center", va="bottom")
    transfer_text = "\n".join(
        f"screen->holdout {row.stage}: {100 * row.adjusted_success_delta:+.1f} pp"
        for row in transfer_rows.itertuples(index=False)
    )
    axis.text(0.02, 0.98, transfer_text, transform=axis.transAxes, va="top", fontsize=9)
    axis.grid(axis="y", alpha=0.25)

    fig.suptitle("Position y0.2 signed value-of-feedback development", fontsize=16)
    fig.tight_layout()
    fig.savefig(output_path, dpi=180)
    plt.close(fig)


def _format_policy(policy: pd.Series | dict[str, object]) -> str:
    get = policy.get
    return (
        f"`{get('model')}` ({get('stage')}, beta={float(get('beta')):.1f}, "
        f"budget={100 * float(get('budget')):.0f}%): "
        f"{int(get('selected_rescues'))} rescue / {int(get('selected_harms'))} harm, "
        f"adjusted delta {100 * float(get('adjusted_success_delta')):+.1f} pp"
    )


