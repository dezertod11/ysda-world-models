def validate_feature_manifest(specs: Sequence[ModelSpec] = MODEL_SPECS) -> None:
    """Reject branch-outcome columns before any model is fitted."""
    allowed_post_prefix = "feedback_query_"
    for spec in specs:
        if spec.stage not in {"pre", "post"}:
            raise ValueError(f"Unknown stage for {spec.name}: {spec.stage}")
        for feature in spec.features:
            lowered = feature.lower()
            if any(fragment in lowered for fragment in FORBIDDEN_FEATURE_FRAGMENTS):
                raise ValueError(f"Outcome leakage in {spec.name}: {feature}")
            if spec.stage == "pre" and feature.startswith(allowed_post_prefix):
                raise ValueError(f"Post-query feature in pre-query model: {feature}")
            if spec.stage == "pre" and feature.startswith("post_"):
                raise ValueError(f"Post-query feature in pre-query model: {feature}")


def _as_bool(series: pd.Series) -> pd.Series:
    if pd.api.types.is_bool_dtype(series):
        return series.fillna(False).astype(bool)
    return series.astype(str).str.strip().str.lower().isin({"1", "true", "yes"})


def _safe_cosine_distance(left: np.ndarray, right: np.ndarray) -> float:
    left_flat = left.reshape(-1)
    right_flat = right.reshape(-1)
    denominator = float(np.linalg.norm(left_flat) * np.linalg.norm(right_flat))
    if denominator <= 1e-12:
        return 0.0
    return float(1.0 - np.dot(left_flat, right_flat) / denominator)


def derive_sidecar_features(path: Path, feedback_steps: int = 8) -> dict[str, float]:
    """Read only decision-time arrays from one counterfactual sidecar."""
    with np.load(path, allow_pickle=False) as payload:
        current_proprio = np.asarray(payload["current_proprio"], dtype=float).reshape(-1)
        old_index = int(np.asarray(payload["selected_max_value_idx"]).item())
        new_index = int(np.asarray(payload["feedback_requery_selected_idx"]).item())
        old_actions = np.asarray(payload["candidate_actions"], dtype=float)
        new_actions = np.asarray(payload["feedback_requery_actions"], dtype=float)
        old_values = np.asarray(payload["candidate_values"], dtype=float)
        new_values = np.asarray(payload["feedback_requery_values"], dtype=float)

    if new_index < 0:
        raise ValueError(f"Sidecar has no feedback re-query: {path}")
    old_tail = old_actions[old_index, feedback_steps : 2 * feedback_steps]
    new_prefix = new_actions[new_index, : len(old_tail)]
    if len(old_tail) == 0 or old_tail.shape != new_prefix.shape:
        raise ValueError(
            f"Cannot align old tail {old_tail.shape} and new prefix {new_prefix.shape}: {path}"
        )
    difference = old_tail - new_prefix
    step_l2 = np.linalg.norm(difference, axis=1)
    sorted_values = np.sort(new_values[np.isfinite(new_values)])
    value_margin = (
        float(sorted_values[-1] - sorted_values[-2]) if len(sorted_values) >= 2 else 0.0
    )
    result = {
        "post_tail_l2_mean": float(step_l2.mean()),
        "post_tail_l2_max": float(step_l2.max()),
        "post_tail_first_l2": float(step_l2[0]),
        "post_tail_xyz_l2_mean": float(np.linalg.norm(difference[:, :3], axis=1).mean()),
        "post_tail_rot_l2_mean": float(np.linalg.norm(difference[:, 3:6], axis=1).mean()),
        "post_tail_gripper_abs_mean": float(np.abs(difference[:, 6]).mean()),
        "post_tail_cosine_distance": _safe_cosine_distance(old_tail, new_prefix),
        "post_tail_sign_disagreement": float(
            np.mean(np.signbit(old_tail) != np.signbit(new_prefix))
        ),
        "post_new_minus_old_value": float(new_values[new_index] - old_values[old_index]),
        "post_new_value_margin": value_margin,
    }
    for index in range(9):
        result[f"pre_current_proprio_d{index}"] = (
            float(current_proprio[index]) if index < len(current_proprio) else float("nan")
        )
    return result


def _sidecar_path(campaign_dir: Path, row: object) -> Path:
    source_run = str(getattr(row, "source_run"))
    sidecar_name = Path(str(getattr(row, "sidecar_path"))).name
    return campaign_dir / "runs" / f"{source_run}__snapshots" / sidecar_name


def _prepare_cohort(
    paired_path: Path,
    campaign_dir: Path,
    *,
    cohort: str,
    condition_id: str,
) -> pd.DataFrame:
    frame = pd.read_parquet(paired_path)
    if "condition_id" in frame:
        frame = frame.loc[frame["condition_id"].eq(condition_id)].copy()
    else:
        frame = frame.loc[
            frame["source_run"].astype(str).str.endswith(f"__{condition_id}")
        ].copy()
    if frame.empty:
        raise ValueError(f"No {condition_id} rows in {paired_path}")

    frame["open_success"] = _as_bool(frame["open_terminal_success"])
    frame["feedback_success"] = _as_bool(frame["feedback_terminal_success"])
    frame["terminal_effect"] = (
        frame["feedback_success"].astype(int) - frame["open_success"].astype(int)
    )
    replay_error = pd.to_numeric(frame["main_open_replay_state_max_abs"], errors="coerce")
    frame["strict_integrity"] = replay_error.le(REPLAY_INTEGRITY_THRESHOLD)
    frame = frame.loc[frame["strict_integrity"]].reset_index(drop=True)
    frame["cohort"] = cohort
    frame["independent_group"] = (
        cohort + "|init" + frame["init_state_id"].astype(int).astype(str)
    )
    frame["analysis_row_id"] = (
        cohort
        + "|"
        + frame["init_state_id"].astype(int).astype(str)
        + "|"
        + frame["rollout_id"].astype(int).astype(str)
    )
    sidecar_rows = []
    for row in frame.itertuples(index=False):
        path = _sidecar_path(campaign_dir, row)
        if not path.is_file():
            raise FileNotFoundError(path)
        feedback_steps = int(getattr(row, "feedback_steps", 8))
        sidecar_rows.append(derive_sidecar_features(path, feedback_steps=feedback_steps))
    return pd.concat([frame, pd.DataFrame(sidecar_rows)], axis=1)


@dataclass
class RidgeModel:
    median: np.ndarray
    mean: np.ndarray
    scale: np.ndarray
    active: np.ndarray
    coefficients: np.ndarray
    covariance: np.ndarray
    residual_scale: float


def _numeric_matrix(frame: pd.DataFrame, features: Sequence[str]) -> np.ndarray:
    missing = [feature for feature in features if feature not in frame]
    if missing:
        raise ValueError(f"Missing model features: {missing}")
    return frame.loc[:, list(features)].apply(pd.to_numeric, errors="coerce").to_numpy(float)


def fit_ridge_model(
    values: np.ndarray, target: np.ndarray, *, alpha: float
) -> RidgeModel:
    finite_columns = np.isfinite(values).any(axis=0)
    if not finite_columns.any():
        raise ValueError("No finite model features")
    selected = values[:, finite_columns]
    median = np.nanmedian(selected, axis=0)
    median = np.where(np.isfinite(median), median, 0.0)
    selected = np.where(np.isfinite(selected), selected, median)
    mean = selected.mean(axis=0)
    scale = selected.std(axis=0)
    varying = scale > 1e-10
    if not varying.any():
        varying[:] = True
        scale[:] = 1.0
    selected = selected[:, varying]
    median = median[varying]
    mean = mean[varying]
    scale = scale[varying]
    standardized = (selected - mean) / scale
    design = np.column_stack([np.ones(len(standardized)), standardized])
    penalty = np.eye(design.shape[1]) * float(alpha)
    penalty[0, 0] = 0.0
    covariance = np.linalg.pinv(design.T @ design + penalty)
    coefficients = covariance @ design.T @ target
    residual = target - design @ coefficients
    residual_scale = float(np.sqrt(np.mean(residual**2)))
    active = np.flatnonzero(finite_columns)[varying]
    return RidgeModel(
        median=median,
        mean=mean,
        scale=scale,
        active=active,
        coefficients=coefficients,
        covariance=covariance,
        residual_scale=residual_scale,
    )


def predict_ridge_model(model: RidgeModel, values: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    selected = values[:, model.active]
    selected = np.where(np.isfinite(selected), selected, model.median)
    standardized = (selected - model.mean) / model.scale
    design = np.column_stack([np.ones(len(standardized)), standardized])
    mean = design @ model.coefficients
    leverage = np.einsum("ij,jk,ik->i", design, model.covariance, design)
    std = model.residual_scale * np.sqrt(np.maximum(1.0 + leverage, 0.0))
    return mean, std


def grouped_oof_predictions(
    frame: pd.DataFrame,
    spec: ModelSpec,
    *,
    group_column: str = "independent_group",
) -> tuple[np.ndarray, np.ndarray]:
    values = _numeric_matrix(frame, spec.features)
    target = frame["terminal_effect"].to_numpy(dtype=float)
    groups = frame[group_column].astype(str).to_numpy()
    means = np.full(len(frame), np.nan, dtype=float)
    stds = np.full(len(frame), np.nan, dtype=float)
    for group in sorted(set(groups)):
        test = groups == group
        train = ~test
        if train.sum() < 8:
            continue
        model = fit_ridge_model(values[train], target[train], alpha=spec.alpha)
        means[test], stds[test] = predict_ridge_model(model, values[test])
    return means, stds


def train_transfer_predictions(
    train: pd.DataFrame, test: pd.DataFrame, spec: ModelSpec
) -> tuple[np.ndarray, np.ndarray]:
    train_values = _numeric_matrix(train, spec.features)
    test_values = _numeric_matrix(test, spec.features)
    model = fit_ridge_model(
        train_values, train["terminal_effect"].to_numpy(float), alpha=spec.alpha
    )
    return predict_ridge_model(model, test_values)


def prediction_diagnostics(
    frame: pd.DataFrame,
    means: np.ndarray,
    *,
    scope: str,
    spec: ModelSpec,
) -> dict[str, object]:
    target = frame["terminal_effect"].to_numpy(float)
    valid = np.isfinite(means)
    discordant = valid & (target != 0)
    correlation = (
        pd.Series(means[valid]).corr(pd.Series(target[valid]), method="spearman")
        if valid.sum() >= 3
        else float("nan")
    )
    return {
        "scope": scope,
        "model": spec.name,
        "stage": spec.stage,
        "alpha": spec.alpha,
        "states": int(valid.sum()),
        "groups": int(frame.loc[valid, "independent_group"].nunique()),
        "features": len(spec.features),
        "rmse": float(np.sqrt(np.mean((means[valid] - target[valid]) ** 2))),
        "spearman_effect": float(correlation),
        "rescue_vs_all_auc": binary_auc(target[valid] > 0, means[valid]),
        "rescue_vs_harm_auc": binary_auc(target[discordant] > 0, means[discordant]),
    }


def _policy_statistics(
    frame: pd.DataFrame,
    selected: np.ndarray,
    *,
    stage: str,
    query_cost: float,
) -> dict[str, object]:
    selected = np.asarray(selected, dtype=bool)
    target = frame["terminal_effect"].to_numpy(float)
    baseline = frame["open_success"].to_numpy(bool)
    query = selected if stage == "pre" else np.ones(len(frame), dtype=bool)
    contributions = selected.astype(float) * target
    adjusted = contributions - query_cost * query.astype(float)
    rescue = target > 0
    harm = target < 0
    rescue_recall = float(selected[rescue].mean()) if rescue.any() else float("nan")
    harm_avoidance = float((~selected[harm]).mean()) if harm.any() else float("nan")
    balanced_accuracy = float(np.nanmean([rescue_recall, harm_avoidance]))
    return {
        "states": len(frame),
        "selected": int(selected.sum()),
        "query_rate": float(query.mean()),
        "selected_rescues": int((selected & rescue).sum()),
        "selected_harms": int((selected & harm).sum()),
        "selected_neutral": int((selected & (target == 0)).sum()),
        "rescue_recall": rescue_recall,
        "harm_avoidance": harm_avoidance,
        "balanced_accuracy": balanced_accuracy,
        "baseline_success_rate": float(baseline.mean()),
        "method_success_rate": float((baseline.astype(float) + contributions).mean()),
        "raw_success_delta": float(contributions.mean()),
        "adjusted_success_delta": float(adjusted.mean()),
    }


def cluster_bootstrap_policy_ci(
    frame: pd.DataFrame,
    selected: np.ndarray,
    *,
    stage: str,
    query_cost: float,
    repetitions: int = DEFAULT_BOOTSTRAP_REPETITIONS,
    seed: int = DEFAULT_BOOTSTRAP_SEED,
) -> tuple[float, float]:
    selected = np.asarray(selected, dtype=bool)
    target = frame["terminal_effect"].to_numpy(float)
    query = selected if stage == "pre" else np.ones(len(frame), dtype=bool)
    contribution = selected.astype(float) * target - query_cost * query.astype(float)
    work = pd.DataFrame(
        {
            "group": frame["independent_group"].astype(str).to_numpy(),
            "sum": contribution,
            "size": 1,
        }
    ).groupby("group", sort=True)[["sum", "size"]].sum()
    values = work.to_numpy(float)
    rng = np.random.default_rng(seed)
    draws = rng.integers(0, len(values), size=(repetitions, len(values)))
    sampled = values[draws]
    effects = sampled[:, :, 0].sum(axis=1) / sampled[:, :, 1].sum(axis=1)
    return tuple(float(value) for value in np.quantile(effects, [0.025, 0.975]))


