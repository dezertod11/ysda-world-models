def policy_tables(
    frame: pd.DataFrame,
    predictions: pd.DataFrame,
    *,
    scope: str,
    query_cost: float,
) -> pd.DataFrame:
    rows: list[dict[str, object]] = []
    baseline_specs = (
        ("always_commit", "pre", np.zeros(len(frame), dtype=bool)),
        ("always_requery", "pre", np.ones(len(frame), dtype=bool)),
        ("oracle_pre", "pre", frame["terminal_effect"].to_numpy(float) > 0),
        ("oracle_post", "post", frame["terminal_effect"].to_numpy(float) > 0),
    )
    for name, stage, selected in baseline_specs:
        row = {
            "scope": scope,
            "model": name,
            "stage": stage,
            "selection_mode": "baseline",
            "beta": float("nan"),
            "budget": float(selected.mean()),
        }
        row.update(_policy_statistics(frame, selected, stage=stage, query_cost=query_cost))
        rows.append(row)

    for model_name, model_predictions in predictions.groupby("model", sort=True):
        stage = str(model_predictions["stage"].iloc[0])
        ordered = frame[["analysis_row_id"]].merge(
            model_predictions[
                ["analysis_row_id", "predicted_vof_mean", "predicted_vof_std"]
            ],
            on="analysis_row_id",
            how="left",
            validate="one_to_one",
        )
        mean = ordered["predicted_vof_mean"].to_numpy(float)
        std = ordered["predicted_vof_std"].to_numpy(float)
        for beta in DEFAULT_BETAS:
            score = mean - beta * std
            natural_threshold = query_cost if stage == "pre" else 0.0
            selected = np.isfinite(score) & (score > natural_threshold)
            row = {
                "scope": scope,
                "model": model_name,
                "stage": stage,
                "selection_mode": "lcb_threshold",
                "beta": beta,
                "budget": float(selected.mean()),
            }
            row.update(
                _policy_statistics(frame, selected, stage=stage, query_cost=query_cost)
            )
            rows.append(row)
            valid = np.flatnonzero(np.isfinite(score))
            for budget in DEFAULT_BUDGETS:
                count = min(len(valid), max(1, int(math.ceil(len(frame) * budget))))
                selected = np.zeros(len(frame), dtype=bool)
                if count:
                    order = valid[np.argsort(score[valid], kind="mergesort")]
                    selected[order[-count:]] = True
                row = {
                    "scope": scope,
                    "model": model_name,
                    "stage": stage,
                    "selection_mode": "ranked_budget",
                    "beta": beta,
                    "budget": budget,
                }
                row.update(
                    _policy_statistics(frame, selected, stage=stage, query_cost=query_cost)
                )
                rows.append(row)
    return pd.DataFrame(rows)


def _selected_mask_from_policy(
    frame: pd.DataFrame, predictions: pd.DataFrame, policy: pd.Series
) -> np.ndarray:
    scoped = predictions.loc[predictions["model"].eq(policy["model"])]
    ordered = frame[["analysis_row_id"]].merge(
        scoped[["analysis_row_id", "predicted_vof_mean", "predicted_vof_std"]],
        on="analysis_row_id",
        how="left",
        validate="one_to_one",
    )
    score = ordered["predicted_vof_mean"].to_numpy(float) - float(policy["beta"]) * ordered[
        "predicted_vof_std"
    ].to_numpy(float)
    if policy["selection_mode"] == "lcb_threshold":
        threshold = DEFAULT_QUERY_COST if policy["stage"] == "pre" else 0.0
        return np.isfinite(score) & (score > threshold)
    valid = np.flatnonzero(np.isfinite(score))
    count = min(len(valid), max(1, int(math.ceil(len(frame) * float(policy["budget"])))))
    selected = np.zeros(len(frame), dtype=bool)
    order = valid[np.argsort(score[valid], kind="mergesort")]
    selected[order[-count:]] = True
    return selected


def _best_development_policy(policies: pd.DataFrame, *, stage: str) -> pd.Series:
    candidates = policies.loc[
        policies["stage"].eq(stage)
        & policies["selection_mode"].eq("ranked_budget")
        & ~policies["model"].str.startswith("oracle")
    ].copy()
    return candidates.sort_values(
        ["adjusted_success_delta", "selected_harms", "query_rate", "model", "beta"],
        ascending=[False, True, True, True, True],
    ).iloc[0]


def _permuted_group_target(frame: pd.DataFrame, rng: np.random.Generator) -> np.ndarray:
    """Permute complete rollout vectors between equally sized init groups."""
    groups = {
        key: np.asarray(list(index), dtype=int)
        for key, index in frame.groupby("independent_group", sort=True).groups.items()
    }
    target = frame["terminal_effect"].to_numpy(float)
    permuted = np.empty_like(target)
    by_size: dict[int, list[str]] = {}
    for key, index in groups.items():
        by_size.setdefault(len(index), []).append(key)
    for keys in by_size.values():
        sources = list(keys)
        rng.shuffle(sources)
        for destination, source in zip(keys, sources):
            permuted[groups[destination]] = target[groups[source]]
    return permuted


def _maximum_prequery_search_gain(
    frame: pd.DataFrame, *, query_cost: float
) -> float:
    best = -float("inf")
    target = frame["terminal_effect"].to_numpy(float)
    pre_specs = [spec for spec in MODEL_SPECS if spec.stage == "pre"]
    for spec in pre_specs:
        mean, std = grouped_oof_predictions(frame, spec)
        for beta in DEFAULT_BETAS:
            score = mean - beta * std
            valid = np.flatnonzero(np.isfinite(score))
            for budget in DEFAULT_BUDGETS:
                count = min(len(valid), max(1, int(math.ceil(len(frame) * budget))))
                order = valid[np.argsort(score[valid], kind="mergesort")]
                selected = np.zeros(len(frame), dtype=bool)
                selected[order[-count:]] = True
                gain = float(
                    np.mean(selected.astype(float) * target)
                    - query_cost * selected.mean()
                )
                best = max(best, gain)
    return best


def selected_model_permutation_test(
    frame: pd.DataFrame,
    *,
    observed_gain: float,
    query_cost: float,
    repetitions: int,
    seed: int,
) -> dict[str, object]:
    """Family-wise null for the complete pre-query model/beta/budget search."""
    rng = np.random.default_rng(seed)
    null = np.empty(repetitions, dtype=float)
    original = frame["terminal_effect"].to_numpy(float).copy()
    work = frame.copy()
    for repetition in range(repetitions):
        work["terminal_effect"] = _permuted_group_target(frame, rng)
        null[repetition] = _maximum_prequery_search_gain(work, query_cost=query_cost)
    work["terminal_effect"] = original
    exceedances = int(np.sum(null >= observed_gain - 1e-12))
    return {
        "repetitions": repetitions,
        "seed": seed,
        "observed_best_adjusted_gain": observed_gain,
        "null_mean_best_adjusted_gain": float(null.mean()),
        "null_p95_best_adjusted_gain": float(np.quantile(null, 0.95)),
        "exceedances": exceedances,
        "familywise_pvalue": float((exceedances + 1) / (repetitions + 1)),
        "null_distribution": null,
    }


def fixed_policy_randomization_test(
    frame: pd.DataFrame,
    selected: np.ndarray,
    *,
    stage: str,
    query_cost: float,
    repetitions: int,
    seed: int,
) -> dict[str, object]:
    """Randomization test for a selection mask fixed without target-cohort labels."""
    selected = np.asarray(selected, dtype=bool)
    observed = float(
        np.mean(selected * frame["terminal_effect"].to_numpy(float))
        - query_cost * (selected.mean() if stage == "pre" else 1.0)
    )
    rng = np.random.default_rng(seed)
    null = np.empty(repetitions, dtype=float)
    for repetition in range(repetitions):
        target = _permuted_group_target(frame, rng)
        null[repetition] = float(
            np.mean(selected * target)
            - query_cost * (selected.mean() if stage == "pre" else 1.0)
        )
    exceedances = int(np.sum(null >= observed - 1e-12))
    return {
        "repetitions": repetitions,
        "seed": seed,
        "observed_adjusted_gain": observed,
        "null_mean_adjusted_gain": float(null.mean()),
        "null_p95_adjusted_gain": float(np.quantile(null, 0.95)),
        "exceedances": exceedances,
        "randomization_pvalue": float((exceedances + 1) / (repetitions + 1)),
        "null_distribution": null,
    }


def _screen_selected_transfer(
    screen: pd.DataFrame,
    holdout: pd.DataFrame,
    screen_predictions: pd.DataFrame,
    holdout_transfer_predictions: pd.DataFrame,
    screen_policies: pd.DataFrame,
    *,
    stage: str,
    query_cost: float,
) -> tuple[dict[str, object], np.ndarray]:
    chosen = _best_development_policy(screen_policies, stage=stage)
    model = str(chosen["model"])
    beta = float(chosen["beta"])
    budget = float(chosen["budget"])
    scoped = holdout_transfer_predictions.loc[
        holdout_transfer_predictions["model"].eq(model)
    ]
    ordered = holdout[["analysis_row_id"]].merge(
        scoped[["analysis_row_id", "predicted_vof_mean", "predicted_vof_std"]],
        on="analysis_row_id",
        how="left",
        validate="one_to_one",
    )
    score = ordered["predicted_vof_mean"].to_numpy(float) - beta * ordered[
        "predicted_vof_std"
    ].to_numpy(float)
    valid = np.flatnonzero(np.isfinite(score))
    count = min(len(valid), max(1, int(math.ceil(len(holdout) * budget))))
    selected = np.zeros(len(holdout), dtype=bool)
    order = valid[np.argsort(score[valid], kind="mergesort")]
    selected[order[-count:]] = True
    result = {
        "source_scope": "screen_loio",
        "target_scope": "screen_to_holdout",
        "model": model,
        "stage": stage,
        "beta": beta,
        "budget": budget,
    }
    result.update(
        _policy_statistics(holdout, selected, stage=stage, query_cost=query_cost)
    )
    ci_low, ci_high = cluster_bootstrap_policy_ci(
        holdout, selected, stage=stage, query_cost=query_cost
    )
    result["adjusted_ci_low"] = ci_low
    result["adjusted_ci_high"] = ci_high
    return result, selected


